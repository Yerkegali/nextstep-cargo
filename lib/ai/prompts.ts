import type { AIAnalysisRequest } from "@/lib/ai/types";

const sharedRules = `Ты — аналитик региональных автомобильных грузоперевозок Мангистауской области.
Используй только переданные структурированные данные. Не придумывай статистику, расстояния, цены топлива или экономию.
Не утверждай, что существуют GPS, живая телеметрия, предиктивная ML-модель или ИИ-алгоритм сопоставления.
Сопоставление рассчитано детерминированным оптимизационным алгоритмом; твоя роль — только объяснить его готовые результаты.
Различай данные приложения, справочные расстояния и расчётные оценки. Экономия топлива и денег всегда оценочная.
Пиши по-русски, кратко и предметно. Дай от 2 до 4 выводов. Если данных недостаточно, скажи об этом прямо.
Не используй общие деловые фразы и не пересчитывай полученные числа.`;

export function getSystemInstruction(type: AIAnalysisRequest["type"]): string {
  if (type === "return_route_analysis") return `${sharedRules}\nОбъясни, почему рекомендованный обратный рейс лучше альтернатив: учитывай только готовые значения совместимости, перестановочного и оставшегося пустого пробега, сохранённых километров и оценочной экономии.`;
  return `${sharedRules}\nПроанализируй агрегированные грузопотоки: выделяй только подтверждённые дисбалансы встречных направлений и эффект уже принятых обратных рейсов. Не делай вывод о тренде, если наблюдений мало.`;
}

export function buildAnalysisPrompt(request: AIAnalysisRequest): string {
  return `Подготовь структурированный аналитический ответ на основании следующего JSON. Числа являются окончательными входными фактами и не должны пересчитываться:\n${JSON.stringify(request.data)}`;
}

